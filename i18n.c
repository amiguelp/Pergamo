#define I18N_SETTINGS_FILE APP_ROOT_DIR "pergamo_settings.cfg"
#define I18N_GLOBAL_CONFIG "/mnt/ext1/system/config/global.cfg"

/* "Automático" sigue el idioma del sistema (global.cfg): español si empieza
   por "es"; cualquier otro idioma, inglés. Si no se puede leer, español. */
static int SystemLanguage(void) {
    FILE *f = fopen(I18N_GLOBAL_CONFIG, "r");
    if (!f) return LANG_ES;
    char line[256];
    int lang = LANG_ES;
    while (fgets(line, sizeof(line), f)) {
        if (strncmp(line, "language=", 9) == 0) {
            lang = strncmp(line + 9, "es", 2) == 0 ? LANG_ES : LANG_EN;
            break;
        }
    }
    fclose(f);
    return lang;
}

int CurrentLanguage(void) {
    if (resolved_language < 0) {
        resolved_language = app_language_setting == LANG_AUTO
            ? SystemLanguage() : app_language_setting;
    }
    return resolved_language;
}

const char *T(const char *es) {
    if (!es || CurrentLanguage() == LANG_ES) return es;
    for (size_t i = 0; i < sizeof(translations) / sizeof(translations[0]); i++) {
        if (strcmp(translations[i].es, es) == 0) return translations[i].en;
    }
    return es;
}

const char *LanguageSettingName(int setting) {
    if (setting == LANG_ES) return "Español";
    if (setting == LANG_EN) return "English";
    return T("Automático");
}

void LoadLanguageSetting(void) {
    FILE *f = fopen(I18N_SETTINGS_FILE, "r");
    app_language_setting = LANG_AUTO;
    if (f) {
        char line[128];
        while (fgets(line, sizeof(line), f)) {
            if (strncmp(line, "language=", 9) == 0) {
                if (strncmp(line + 9, "es", 2) == 0) app_language_setting = LANG_ES;
                else if (strncmp(line + 9, "en", 2) == 0) app_language_setting = LANG_EN;
            }
        }
        fclose(f);
    }
    resolved_language = -1;
}

void SetLanguageSetting(int setting) {
    app_language_setting = setting;
    resolved_language = -1;
    FILE *f = fopen(I18N_SETTINGS_FILE, "w");
    if (!f) return;
    fprintf(f, "language=%s\n", setting == LANG_ES ? "es" : setting == LANG_EN ? "en" : "auto");
    fclose(f);
}
